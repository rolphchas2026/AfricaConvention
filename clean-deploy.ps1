Write-Host "??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "???    AFRICA CONVENTION 2026 - INTEGRATED SYSTEM           ???" -ForegroundColor Cyan
Write-Host "???  ALFIO Ticketing + QR Check-in System                    ???" -ForegroundColor Cyan
Write-Host "??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Check prerequisites
Write-Host " Checking prerequisites..." -ForegroundColor Yellow

# Check Docker
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Write-Host " Docker not found. Please install Docker Desktop." -ForegroundColor Red
    exit 1
}
Write-Host " Docker found: $(docker --version)" -ForegroundColor Green

# Check Docker Compose
if (-not (Get-Command docker-compose -ErrorAction SilentlyContinue)) {
    Write-Host " Docker Compose not found." -ForegroundColor Red
    exit 1
}
Write-Host " Docker Compose found" -ForegroundColor Green
Write-Host ""

# Navigate to project directory
$projectPath = "C:\AfricaConvention"
if (-not (Test-Path $projectPath)) {
    Write-Host " Project directory not found: $projectPath" -ForegroundColor Red
    Write-Host "Please create the directory and copy files there." -ForegroundColor Yellow
    exit 1
}

Set-Location $projectPath
Write-Host " Working directory: $projectPath" -ForegroundColor Cyan
Write-Host ""

# Backup existing files
Write-Host " Creating backups..." -ForegroundColor Yellow
if (Test-Path "docker-compose.yml") {
    Copy-Item "docker-compose.yml" "docker-compose-BACKUP-$(Get-Date -Format 'yyyyMMdd-HHmmss').yml" -Force
    Write-Host " Backed up docker-compose.yml" -ForegroundColor Green
}
if (Test-Path ".env") {
    Copy-Item ".env" ".env-BACKUP-$(Get-Date -Format 'yyyyMMdd-HHmmss')" -Force
    Write-Host " Backed up .env" -ForegroundColor Green
}
Write-Host ""

# File renaming
Write-Host " Renaming files..." -ForegroundColor Yellow

$fileRenames = @(
    @{old = "docker-compose-INTEGRATED.yml"; new = "docker-compose.yml"},
    @{old = "qr-server-integrated.js"; new = "qr-server-api.js"},
    @{old = ".env-integrated"; new = ".env"}
)

foreach ($rename in $fileRenames) {
    if (Test-Path $rename.old) {
        Rename-Item $rename.old $rename.new -Force
        Write-Host " Renamed: $($rename.old) ??? $($rename.new)" -ForegroundColor Green
    } else {
        Write-Host "  File not found: $($rename.old)" -ForegroundColor Yellow
    }
}
Write-Host ""

# Docker cleanup
Write-Host " Cleaning up old containers..." -ForegroundColor Yellow
docker-compose down -v 2>$null
Write-Host " Old containers removed" -ForegroundColor Green
Write-Host ""

# Build and start
Write-Host " Building and starting services..." -ForegroundColor Cyan
Write-Host "This may take 2-3 minutes..." -ForegroundColor Yellow
Write-Host ""

docker-compose build --no-cache
if ($LASTEXITCODE -ne 0) {
    Write-Host " Build failed" -ForegroundColor Red
    exit 1
}

Write-Host ""
Write-Host "Starting containers..." -ForegroundColor Cyan
docker-compose up -d

# Wait for services
Write-Host ""
Write-Host "Waiting for services to start 30 seconds" -ForegroundColor Cyan
Start-Sleep -Seconds 30

# Verify services
Write-Host ""
Write-Host " Checking service status..." -ForegroundColor Cyan
docker-compose ps

Write-Host ""
Write-Host "??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????" -ForegroundColor Green
Write-Host "???   SYSTEM READY FOR OPERATION                           ???" -ForegroundColor Green
Write-Host "??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????" -ForegroundColor Green
Write-Host ""

# Display access URLs
Write-Host " ACCESS POINTS:" -ForegroundColor Cyan
Write-Host "  ??? ALFIO Ticketing:      http://localhost:9090" -ForegroundColor White
Write-Host "  ??? QR Check-in System:   http://localhost:3000" -ForegroundColor White
Write-Host "  ??? Supervisor Dashboard: http://localhost:4000" -ForegroundColor White
Write-Host "  ??? Shared Database:      localhost:5432" -ForegroundColor White
Write-Host ""

# Display credentials
Write-Host " DATABASE CREDENTIALS:" -ForegroundColor Cyan
Write-Host "  ??? User: admin" -ForegroundColor White
Write-Host "  ??? Password: ArushaPassword2026" -ForegroundColor White
Write-Host "  ??? Database: africa_convention" -ForegroundColor White
Write-Host ""

# Next steps
Write-Host " NEXT STEPS:" -ForegroundColor Yellow
Write-Host "  1. Open http://localhost:9090 in browser (ALFIO)" -ForegroundColor White
Write-Host "  2. Create event and generate QR codes" -ForegroundColor White
Write-Host "  3. Open http://localhost:3000 for QR scanning" -ForegroundColor White
Write-Host "  4. Open http://localhost:4000 for real-time monitoring" -ForegroundColor White
Write-Host ""

# Display useful commands
Write-Host " USEFUL COMMANDS:" -ForegroundColor Yellow
Write-Host "  View logs:              docker-compose logs -f" -ForegroundColor White
Write-Host "  Restart services:       docker-compose restart" -ForegroundColor White
Write-Host "  Stop everything:        docker-compose down" -ForegroundColor White
Write-Host "  Check service status:   docker-compose ps" -ForegroundColor White
Write-Host ""

Write-Host " TROUBLESHOOTING:" -ForegroundColor Yellow
Write-Host "  ??? See INTEGRATION-GUIDE.md for detailed documentation" -ForegroundColor White
Write-Host "Check logs if services do not start properly" -ForegroundColor White
Write-Host "  ??? Ensure ports 9090, 3000, 4000, 5432 are available" -ForegroundColor White
Write-Host ""

Write-Host " Your integrated event management system is ready!" -ForegroundColor Green
